def main():
    base_dir = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
    results_dir = os.path.join(base_dir, "results")

    df_before = pd.read_csv(os.path.join(results_dir, "telemetry_before_tuning.csv"))
    df_zn     = pd.read_csv(os.path.join(results_dir, "telemetry_zn_tuning.csv"))
    df_after  = pd.read_csv(os.path.join(results_dir, "pid_telemetry_log.csv"))
    df_sched  = pd.read_csv(os.path.join(results_dir, "rtos_task_schedule_log.csv"))

    m_before, m_zn, m_after = generate_step_and_disturbance_plot(
        df_before, df_zn, df_after,
        os.path.join(results_dir, "pid_step_and_disturbance_response.png"),
    )
    generate_rtos_timing_plot(
        df_sched,
        os.path.join(results_dir, "rtos_task_timing_analysis.png"),
    )
    write_markdown_report(
        m_before, m_zn, m_after,
        os.path.join(results_dir, "control_and_rtos_report.md"),
    )
    print("Successfully generated plots and control_and_rtos_report.md in results/.")


if __name__ == "__main__":
    main()
